"""Compact visual review of a captured export selection."""
from pathlib import Path
from PySide6 import QtCore, QtGui, QtWidgets as W


class ExportReviewDialog(W.QDialog):
    def __init__(self, studio, records, cross=False):
        super().__init__(studio)
        english = studio.preferences.get('language') == 'en'
        def t(es, en):
            return en if english else es
        self.setWindowTitle(t('Revisar exportación', 'Review export'))
        self.resize(820, 600)
        self.setMinimumSize(740, 520)
        root = W.QVBoxLayout(self)
        root.setContentsMargins(24, 22, 24, 22)
        root.setSpacing(16)
        title = W.QLabel(t('Todo listo para intercambiar', 'Ready to swap'))
        title.setObjectName('ShelfTitle')
        root.addWidget(title)
        source = W.QFrame()
        source.setObjectName('StepCard')
        source_row = W.QHBoxLayout(source)
        source_row.setContentsMargins(16, 10, 16, 10)
        image = W.QLabel()
        image.setFixedSize(44, 56)
        image.setPixmap(QtGui.QPixmap(studio.source.get('image', '')).scaled(
            image.size(), QtCore.Qt.AspectRatioMode.KeepAspectRatio,
            QtCore.Qt.TransformationMode.SmoothTransformation))
        source_row.addWidget(image)
        source_text = W.QVBoxLayout()
        eyebrow = W.QLabel(t('MOD DE ORIGEN', 'SOURCE MOD'))
        eyebrow.setObjectName('Muted')
        source_text.addWidget(eyebrow)
        filename = W.QLabel(Path(studio.mod_info['path']).name)
        filename.setWordWrap(True)
        filename.setObjectName('SelectionName')
        source_text.addWidget(filename)
        source_row.addLayout(source_text, 1)
        root.addWidget(source)

        content = W.QHBoxLayout()
        content.setSpacing(18)
        destinations = W.QVBoxLayout()
        destinations.addWidget(W.QLabel(t(f'{len(records)} trajes de destino', f'{len(records)} destination costumes')))
        self.destinations = W.QListWidget()
        self.destinations.setSelectionMode(W.QAbstractItemView.SelectionMode.NoSelection)
        self.destinations.setIconSize(QtCore.QSize(48, 62))
        self.destinations.setSpacing(4)
        self.destinations.setHorizontalScrollBarPolicy(QtCore.Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        for record in records:
            item = W.QListWidgetItem(QtGui.QIcon(record.get('image', '')),
                                    record['name'] + '\n' + record['character'] + ' · ' + str(record.get('id', '')))
            item.setSizeHint(QtCore.QSize(250, 84))
            item.setToolTip(record['skin_path'])
            self.destinations.addItem(item)
        destinations.addWidget(self.destinations, 1)
        content.addLayout(destinations, 1)

        options = W.QFrame()
        options.setObjectName('StepCard')
        options.setFixedWidth(292)
        settings = W.QVBoxLayout(options)
        settings.setContentsMargins(16, 16, 16, 16)
        settings.setSpacing(12)
        heading = W.QLabel(t('Organiza tu exportación', 'Organize your export'))
        heading.setObjectName('SelectionName')
        settings.addWidget(heading)
        self.create_folder = W.QCheckBox(t('Crear carpeta para este lote', 'Create batch folder'))
        settings.addWidget(self.create_folder)
        self.folder_options = W.QWidget()
        self.folder_options.setObjectName('FolderOptions')
        self.folder_options.setStyleSheet('#FolderOptions { background: transparent; }')
        folder_layout = W.QVBoxLayout(self.folder_options)
        folder_layout.setContentsMargins(0, 0, 0, 0)
        self.folder_mode = W.QComboBox()
        self.folder_mode.addItems([t('Personaje', 'Character'), t('Nombre del mod', 'Mod name'), t('Personalizado', 'Custom')])
        folder_layout.addWidget(self.folder_mode)
        default_name = studio.source['character'] + t(' - Intercambios', ' - Swaps')
        self.folder_name = W.QLineEdit(default_name)
        self.folder_name.setAccessibleName(t('Nombre de la carpeta', 'Folder name'))
        folder_layout.addWidget(self.folder_name)
        self.folder_options.setEnabled(False)
        self.create_folder.toggled.connect(self.folder_options.setEnabled)
        settings.addWidget(self.folder_options)

        def name_folder(index):
            from services.filename_service import split_known_suffix, split_counter_suffix, extract_parenthesized_groups
            if index == 0:
                self.folder_name.setText(default_name)
            elif index == 1:
                stem, _ = split_counter_suffix(Path(studio.mod_info['path']).stem)
                stem, _ = split_known_suffix(stem)
                name, _ = extract_parenthesized_groups(stem)
                self.folder_name.setText(name.strip() or stem)
        self.folder_mode.currentIndexChanged.connect(name_folder)
        self.grouped = W.QCheckBox(t('Separar por personaje', 'Group by character'))
        settings.addWidget(self.grouped)
        hint = W.QLabel(t('Sin estas opciones, los PAK se guardan directamente en la carpeta que elijas.',
                          'With these options off, PAK files go directly into your chosen folder.'))
        hint.setWordWrap(True)
        hint.setObjectName('Muted')
        settings.addWidget(hint)
        settings.addStretch()
        self.acknowledge = W.QCheckBox(t('Confirmar cruce de personajes', 'Confirm cross-character swap'))
        self.acknowledge.setVisible(cross)
        settings.addWidget(self.acknowledge)
        content.addWidget(options)
        root.addLayout(content, 1)
        note = W.QLabel(t('Tu PAK original se conserva. Los nombres repetidos reciben un contador.',
                         'Your original PAK is preserved. Duplicate names receive a counter.'))
        note.setWordWrap(True)
        note.setObjectName('Muted')
        root.addWidget(note)
        buttons = W.QHBoxLayout()
        buttons.addStretch()
        cancel = W.QPushButton(t('Cancelar', 'Cancel'))
        cancel.clicked.connect(self.reject)
        buttons.addWidget(cancel)
        self.export_button = W.QPushButton(t('Elegir carpeta y exportar', 'Choose folder and export'))
        self.export_button.setObjectName('Primary')
        self.export_button.setEnabled(not cross)
        self.export_button.setDefault(True)
        self.acknowledge.toggled.connect(self.export_button.setEnabled)
        self.export_button.clicked.connect(self.accept)
        buttons.addWidget(self.export_button)
        root.addLayout(buttons)
