"""Import-first screens with a scroll fallback for small displays."""
from PySide6 import QtCore, QtWidgets as W
from ui.studio_base import StudioBase, label


class StudioLayout(StudioBase):
    def __init__(self):
        super().__init__()
        self.resize(1200, 720)
        self.setMinimumSize(860, 500)
        self.records = []
        self.source = self.target = None
        self.dark = True
        self.scroll = W.QScrollArea()
        self.scroll.setWidgetResizable(True)
        self.scroll.setFrameShape(W.QFrame.Shape.NoFrame)
        self.root = W.QWidget()
        self.root.setObjectName('Canvas')
        self.root.setMinimumWidth(830)
        self.scroll.setWidget(self.root)
        self.setCentralWidget(self.scroll)
        page = W.QVBoxLayout(self.root)
        page.setContentsMargins(22, 16, 22, 16)
        page.setSpacing(12)
        top = W.QHBoxLayout()
        from ui.animated_wordmark import AnimatedWordmark
        self.wordmark = AnimatedWordmark()
        top.addWidget(self.wordmark)

        top.addStretch()
        self.tabs = W.QFrame()
        self.tabs.setObjectName('Segment')
        self.tabs.setMinimumHeight(52)
        tl = W.QHBoxLayout(self.tabs)
        tl.setContentsMargins(5, 5, 5, 5)
        self.tab_group = W.QButtonGroup(self)
        for index, title in [(0, 'Trajes'), (3, 'Cola'), (1, 'Entre personajes'), (2, 'Herramientas')]:
            button = W.QPushButton(title)
            button.setCheckable(True)
            button.setChecked(index == 0)
            button.setMinimumHeight(22)
            self.tab_group.addButton(button, index)
            tl.addWidget(button)
        self.tab_group.idClicked.connect(self.change_tab)
        top.addWidget(self.tabs)
        top.addStretch()
        self.theme_button = W.QPushButton('White')
        self.theme_button.setObjectName('ThemeSwitch')
        self.theme_button.clicked.connect(lambda: self.set_theme(not self.dark))
        top.addWidget(self.theme_button)
        self.accent_combo = W.QComboBox()
        for title, color in [('Blue','#0a84ff'),('Violet','#8b5cf6'),('Rose','#db2777'),('Emerald','#008a63'),('Amber','#a36500')]:
            self.accent_combo.addItem(title,color)
        self.accent_combo.currentIndexChanged.connect(lambda: self.set_theme(self.dark))
        top.addWidget(self.accent_combo)
        self.language_combo = W.QComboBox()
        self.language_combo.addItem('Español', 'es')
        self.language_combo.addItem('English', 'en')
        top.addWidget(self.language_combo)
        self.new_session = W.QPushButton('+ Mod')
        self.new_session.clicked.connect(self.open_session)
        top.addWidget(self.new_session)
        page.addLayout(top)

        self.pages = W.QStackedWidget()
        page.addWidget(self.pages, 1)
        self.home = W.QWidget()
        welcome_outer = W.QVBoxLayout(self.home)
        welcome_outer.setContentsMargins(0, 12, 0, 0)
        hero = W.QFrame()
        hero.setObjectName('WelcomeHero')
        welcome_outer.addWidget(hero, 1)
        welcome = W.QVBoxLayout(hero)
        welcome.setContentsMargins(40, 24, 40, 24)
        welcome.setSpacing(18)
        welcome.addStretch()
        welcome.addWidget(label('TU MOD. TU ESTILO.', 'WelcomeEyebrow'))
        self.heading = label('Cambia de traje.', 'Headline')
        welcome.addWidget(self.heading)
        self.home_description = label('Importa tu mod. Te mostraremos únicamente los trajes de su personaje.', 'ShelfTitle')
        welcome.addWidget(self.home_description)
        self.home_hint = label('1. Importa un PAK     2. Elige el traje     3. Exporta tu mod', 'Muted')
        welcome.addWidget(self.home_hint)
        self.home_import = W.QPushButton('+  Importar mod PAK')
        self.home_import.setObjectName('Primary')
        self.home_import.clicked.connect(self.pick_mod)
        welcome.addWidget(self.home_import, alignment=QtCore.Qt.AlignmentFlag.AlignLeft)
        self.catalog_button = W.QPushButton('Actualizar catálogo / Update catalog')
        self.catalog_button.clicked.connect(self.tool_catalog)
        welcome.addWidget(self.catalog_button, alignment=QtCore.Qt.AlignmentFlag.AlignLeft)
        welcome.addStretch()
        welcome.addWidget(label('También puedes arrastrar tu archivo .pak a esta ventana.', 'Muted'))
        self.pages.addWidget(self.home)

        self.workspace = W.QWidget()
        workspace_outer = W.QHBoxLayout(self.workspace)
        workspace_outer.setContentsMargins(0, 0, 0, 0)
        workspace_outer.setSpacing(16)
        self.catalog_panel = W.QWidget()
        self.workspace_layout = W.QVBoxLayout(self.catalog_panel)
        workspace_outer.addWidget(self.catalog_panel, 1)
        self.workspace_layout.setContentsMargins(0, 0, 0, 0)
        self.workspace_layout.setSpacing(10)
        self.stage = W.QFrame()
        self.stage.setObjectName('Stage')
        self.stage.setFixedWidth(224)
        workspace_outer.addWidget(self.stage)
        sl = W.QVBoxLayout(self.stage)
        sl.setContentsMargins(18, 20, 18, 20)
        sl.setSpacing(10)
        self.source_image = W.QLabel()
        self.source_image.setFixedSize(120, 132)
        self.source_image.setAlignment(QtCore.Qt.AlignmentFlag.AlignCenter)
        sl.addWidget(self.source_image, alignment=QtCore.Qt.AlignmentFlag.AlignHCenter)
        source = W.QVBoxLayout()
        self.category_label = label('MOD IMPORTADO · INTERCAMBIO DE TRAJE', 'StageEyebrow')
        source.addWidget(self.category_label)
        self.source_title = label('', 'SelectionName')
        source.addWidget(self.source_title)
        self.source_id = label('', 'StageMuted')
        source.addWidget(self.source_id)
        sl.addLayout(source)
        self.source_action = W.QPushButton('Cambiar malla')
        self.source_action.clicked.connect(self.set_source)
        sl.addWidget(self.source_action)
        self.import_button = W.QPushButton('Cambiar mod')
        self.import_button.clicked.connect(self.pick_mod)
        sl.addWidget(self.import_button)
        sl.addStretch(1)

        self.catalog_heading = W.QHBoxLayout()
        self.shelf_title = label('Elige el traje de destino', 'ShelfTitle')
        self.catalog_heading.addWidget(self.shelf_title, 1)
        self.catalog_shortcut = W.QPushButton('Actualizar catálogo')
        self.catalog_shortcut.clicked.connect(self.tool_catalog)
        self.catalog_heading.addWidget(self.catalog_shortcut)
        self.workspace_layout.addLayout(self.catalog_heading)
        filters = W.QHBoxLayout()
        self.search = W.QLineEdit()
        self.search.setPlaceholderText('Buscar traje o ID')
        self.search.setClearButtonEnabled(True)
        self.search.setAccessibleName('Buscar traje o ID · Ctrl+F')
        self.search.textChanged.connect(self.filter_records)
        filters.addWidget(self.search, 1)
        self.character = W.QComboBox()
        self.character.setMinimumWidth(160)
        self.character.addItem('Elige personaje…', '')
        self.character.currentIndexChanged.connect(self.filter_records)
        filters.addWidget(self.character)
        self.workspace_layout.addLayout(filters)
        self.order_combo = W.QComboBox()
        self.order_combo.addItem('Orden: ID', 'id')
        self.order_combo.addItem('Orden: nombre', 'name')
        self.order_combo.addItem('Orden: nombre interno', 'internal')
        self.kind_combo = W.QComboBox()
        self.kind_combo.addItem('Todos los trajes', 'all')
        self.kind_combo.addItem('Traje actual', 'current')
        self.kind_combo.addItem('Sin identificar', 'unknown')
        filters.addWidget(self.order_combo)
        filters.addWidget(self.kind_combo)
        self.selection_toolbar = W.QHBoxLayout()
        self.workspace_layout.addLayout(self.selection_toolbar)
        self.count = label('', 'Muted')
        sl.addWidget(self.count)

        self.grid = W.QListWidget()
        self.grid.setViewMode(W.QListView.ViewMode.IconMode)
        self.grid.setResizeMode(W.QListView.ResizeMode.Adjust)
        self.grid.setMovement(W.QListView.Movement.Static)
        self.grid.setWrapping(True)
        self.grid.setIconSize(QtCore.QSize(154, 144))
        self.grid.setGridSize(QtCore.QSize(190, 210))
        self.grid.setSpacing(8)
        self.grid.setWordWrap(True)
        self.grid.setMinimumHeight(150)
        self.grid.currentItemChanged.connect(self.inspect)
        self.workspace_layout.addWidget(self.grid, 1)
        self.dock = W.QFrame()
        self.dock.setObjectName('Dock')
        dl = W.QHBoxLayout(self.dock)
        dl.setContentsMargins(16, 10, 16, 10)
        self.selection_image = W.QLabel()
        self.selection_image.setFixedSize(42, 48)
        dl.addWidget(self.selection_image)
        summary = W.QVBoxLayout()
        self.selection_name = label('Elige un traje', 'SelectionName')
        self.status = label('', 'Muted')
        summary.addWidget(self.selection_name)
        self.selection_details = label('', 'Muted')
        summary.addWidget(self.selection_details)
        summary.addWidget(self.status)
        dl.addLayout(summary, 1)
        self.review = W.QPushButton('Exportar traje →')
        self.review.setObjectName('Primary')
        self.review.clicked.connect(self.review_swap)
        dl.addWidget(self.review)
        self.dock.hide()
        sl.addWidget(self.status)
        self.pages.addWidget(self.workspace)
        self.mode = W.QComboBox(self)
        self.mode.addItems(['Traje → Traje', 'Personaje → Personaje'])
        self.mode.hide()
        # Compatibility for state updates; these are not additional visible panels.
        self.target_image = W.QLabel(self)
        self.target_title = W.QLabel(self)
        self.target_id = W.QLabel(self)
        for widget in (self.target_image, self.target_title, self.target_id):
            widget.hide()
        self.load_records()
        self.filter_records()
        self.set_theme(True)
        self.pages.setCurrentWidget(self.home)
